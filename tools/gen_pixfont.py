#!/usr/bin/env python3
"""Pixel fonts for the pause menu (src/hm_pixfont.h).

The menu is drawn at the SNES's own resolution (256x224) and doubled, so its
text has to be real pixel type, one bit per pixel, no smoothing. Two open
fonts (SIL Open Font License, tools/fonts/OFL-*.txt):

    body   Pixelify Sans, 11 px
    small  Tiny5, 8 px

Glyphs the fonts lack (the arrows, the heart) are drawn here by hand.
Run:  python3 tools/gen_pixfont.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "hm_pixfont.h")

FONTS = [
    ("body", "PixelifySans-Regular.ttf", 11),
    ("small", "Tiny5-Regular.ttf", 8),
]
CODEPOINTS = list(range(32, 127)) + list(range(0xA0, 0x100))

# Hand-drawn extras, '#' = ink. Placed on the baseline like a capital.
EXTRA = {
    0x2194: ["..#...#..",   # left-right arrow
             ".##...##.",
             "#########",
             ".##...##.",
             "..#...#.."],
    0x2665: [".##.##.",     # heart
             "#######",
             "#######",
             ".#####.",
             "..###..",
             "...#..."],
    0x25B6: ["#...",        # right-pointing triangle
             "##..",
             "###.",
             "##..",
             "#..."],
    0x25BC: ["#####",       # down-pointing triangle
             ".###.",
             "..#.."],
}


def render(font_file, size):
    font = ImageFont.truetype(os.path.join(HERE, "fonts", font_file), size)
    ascent, descent = font.getmetrics()
    h = ascent + descent
    glyphs = []
    cmap = set()
    try:
        from fontTools.ttLib import TTFont
        cmap = set(TTFont(os.path.join(HERE, "fonts", font_file)).getBestCmap())
    except Exception:
        pass
    for cp in CODEPOINTS:
        if cmap and cp not in cmap and cp != 32:
            continue
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        w = max(adv, 1) + 2
        im = Image.new("1", (w + 4, h), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((0, 0), ch, font=font, fill=1)
        rows = []
        for y in range(h):
            bits = 0
            for x in range(min(w + 4, 16)):
                if im.getpixel((x, y)):
                    bits |= 1 << x
            rows.append(bits)
        glyphs.append((cp, adv, rows))
    cap_top = ascent - size * 7 // 10           # where a capital starts
    for cp, art in EXTRA.items():
        rows = [0] * h
        top = max(0, ascent - len(art))
        for j, line in enumerate(art):
            bits = 0
            for x, c in enumerate(line):
                if c == "#":
                    bits |= 1 << x
            if top + j < h:
                rows[top + j] = bits
        glyphs.append((cp, len(art[0]) + 1, rows))
    return h, ascent, glyphs


def main():
    out = ["/* Generated by tools/gen_pixfont.py -- do not edit.",
           " * Pixelify Sans and Tiny5, SIL Open Font License 1.1",
           " * (tools/fonts/OFL-*.txt). One bit per pixel, bit 0 = leftmost. */",
           "#pragma once", "#include <stdint.h>", "",
           "typedef struct { uint16_t cp; uint8_t adv; uint16_t off; } HmPixGlyph;",
           "typedef struct { int h, ascent, n; const HmPixGlyph *g; const uint16_t *rows; } HmPixFont;",
           ""]
    for name, file, size in FONTS:
        h, ascent, glyphs = render(file, size)
        rows, table = [], []
        for cp, adv, r in glyphs:
            table.append("{0x%04X,%d,%d}" % (cp, adv, len(rows)))
            rows.extend(r)
        out.append("static const uint16_t kPix_%s_rows[%d] = {" % (name, len(rows)))
        for i in range(0, len(rows), 16):
            out.append("  " + ",".join("0x%04X" % v for v in rows[i:i + 16]) + ",")
        out.append("};")
        out.append("static const HmPixGlyph kPix_%s_glyphs[%d] = {" % (name, len(table)))
        for i in range(0, len(table), 8):
            out.append("  " + ",".join(table[i:i + 8]) + ",")
        out.append("};")
        out.append("static const HmPixFont kPix_%s = { %d, %d, %d, kPix_%s_glyphs, kPix_%s_rows };"
                   % (name, h, ascent, len(table), name, name))
        out.append("")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()

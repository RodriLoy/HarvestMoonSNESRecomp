#!/usr/bin/env python3
"""Rasterize DejaVu Sans into src/hm_font.h: proportional 8-bit alpha glyphs
for the pause menu, covering ASCII plus the Latin-1 letters (Spanish,
Italian, French, Portuguese, German...) its translations use.

    python3 tools/gen_font.py [path/to/DejaVuSans-Bold.ttf]

DejaVu fonts are under the Bitstream Vera / DejaVu free license (see
THIRD_PARTY notice in the generated header). Only a bitmap of the glyphs is
embedded; regenerate instead of editing the header.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
EXTRA = "".join(chr(c) for c in range(0xC0, 0x100) if c not in (0xD7, 0xF7)) + "¿¡°·×♥↔"
CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA)
SIZES = {"small": 11, "body": 13, "title": 19}

out = ["/* Generated by tools/gen_font.py from DejaVu Sans Bold -- do not edit.",
       " * DejaVu fonts: Copyright (c) 2003 Bitstream, Inc. (Bitstream Vera) and",
       " * DejaVu changes are in the public domain; free license, see",
       " * https://dejavu-fonts.github.io/License.html */",
       "#pragma once", "#include <stdint.h>", "",
       "typedef struct { uint32_t cp; uint8_t w, adv; uint32_t off; } HmGlyph;",
       "typedef struct { uint8_t h, ascent; int n; const HmGlyph *g; const uint8_t *a; } HmFont;", ""]
for name, px in SIZES.items():
    font = ImageFont.truetype(TTF, px)
    ascent, descent = font.getmetrics()
    h = ascent + descent
    glyphs, alpha = [], []
    for ch in CHARS:
        if ch in "♥↔":
            try:
                f2 = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", px)
            except OSError:
                f2 = font
            f = f2
        else:
            f = font
        adv = max(1, round(f.getlength(ch)))
        w = adv + 2
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((1, 0), ch, font=f, fill=255)
        glyphs.append((ord(ch), w, adv, len(alpha)))
        alpha.extend(im.tobytes())
    out.append(f"static const uint8_t kHmFontAlpha_{name}[{len(alpha)}] = {{")
    for i in range(0, len(alpha), 24):
        out.append("  " + ",".join(str(v) for v in alpha[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const HmGlyph kHmFontGlyphs_{name}[{len(glyphs)}] = {{")
    for cp, w, adv, off in glyphs:
        out.append(f"  {{0x{cp:X}, {w}, {adv}, {off}}},")
    out.append("};")
    out.append(f"static const HmFont kHmFont_{name} = {{ {h}, {ascent}, {len(glyphs)}, "
               f"kHmFontGlyphs_{name}, kHmFontAlpha_{name} }};")
    out.append("")
open(sys.argv[2] if len(sys.argv) > 2 else "src/hm_font.h", "w").write("\n".join(out) + "\n")
print("wrote", len(CHARS), "glyphs x", len(SIZES), "sizes")
